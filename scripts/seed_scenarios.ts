async function seed() {
  console.log('Connecting to MongoDB...');
  await db();

  const mentorEmail = (process.env.SEED_MENTOR_EMAIL || 'mentor@britinstitute.co.uk').toLowerCase();
  const mentor = await User.findOne({ email: mentorEmail });
  if (!mentor) {
    throw new Error('Mentor user not found. Please run npm run seed first.');
  }

  console.log('Found mentor:', mentor.email);

  const createdQuestions = [];
  for (const qData of questionsData) {
    const q = await Question.findOneAndUpdate(
      { externalId: qData.externalId },
      {
        $set: {
          ...qData,
          createdBy: mentor._id,
          version: 1,
        },
      },
      { upsert: true, new: true }
    );
    createdQuestions.push(q);
    console.log(`Seeded question: [${q.externalId}] ${q.topics.join(', ')}`);
  }

  // Create or update Daily Test for today
  const date = todayUK();
  console.log(`Setting up Daily Test for today (${date})...`);

  const testTitle = 'Daily Assessment — Data Analytics Excel Case Study (Sales & Profitability)';

  const items = createdQuestions.map((q) => ({
    questionId: q._id,
    snapshot: {
      type: q.type,
      subject: q.subject,
      topics: q.topics,
      tags: q.tags,
      difficulty: q.difficulty,
      questionText: q.questionText,
      mediaIds: q.mediaIds,
      options: q.options,
      correctOptionKeys: q.correctOptionKeys,
      explanation: q.explanation,
      version: q.version,
    },
  }));

  const dailyTest = await DailyTest.findOneAndUpdate(
    { testDate: date, title: testTitle },
    {
      $set: {
        title: testTitle,
        testDate: date,
        releaseAt: releaseDate(date),
        batchId: 'all',
        status: 'published',
        createdBy: mentor._id,
        items,
      },
    },
    { upsert: true, new: true }
  );

  console.log(`Daily Test ready: ID = ${dailyTest._id}, Title = "${dailyTest.title}", Questions = ${dailyTest.items.length}`);

  // Clear any previous attempts by learner so they can test fresh
  const learnerEmail = (process.env.SEED_LEARNER_EMAIL || 'learner@example.com').toLowerCase();
  const learner = await User.findOne({ email: learnerEmail });
  if (learner) {
    const deleted = await TestAttempt.deleteMany({ learnerId: learner._id, testId: dailyTest._id });
    if (deleted.deletedCount > 0) {
      console.log(`Reset previous learner attempt for clean test-taking.`);
    }
  }

  console.log('\nAll 5 scenario questions seeded successfully into the database!');
  console.log(`Learners can log in with ${learnerEmail} and take this test today under Daily Tests.`);

  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error('Seeding error:', err);
  process.exit(1);
});

